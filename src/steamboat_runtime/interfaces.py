"""Common synchronous session contract; RPC and scheduling arrive in later phases."""

from typing import Any, Protocol, TYPE_CHECKING

if TYPE_CHECKING:
    from torch import Tensor


class InferenceSession(Protocol):
    position: int

    def step(self, input_ids: "Tensor", *, return_all_logits: bool = False) -> "Tensor": ...
    def close(self) -> None: ...
    def diagnostics(self) -> dict[str, Any]: ...
    def __enter__(self) -> "InferenceSession": ...
    def __exit__(self, *exc: Any) -> None: ...


class InferenceBackend(Protocol):
    def open_session(self, max_length: int) -> InferenceSession: ...
    def diagnostics(self) -> dict[str, Any]: ...
