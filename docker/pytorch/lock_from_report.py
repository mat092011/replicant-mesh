"""Render pip's resolution report as an exact, wheel-only SHA256 lock.

Run resolution in the pinned Docker base; the lock is intentionally specific to
CPython 3.12 on Linux amd64. No resolver is needed during subsequent image builds.
"""

import argparse
import json
import re
from pathlib import Path
from urllib.parse import urlparse


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("report", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    report = json.loads(args.report.read_text(encoding="utf-8"))
    environment = report["environment"]
    if (environment["python_version"], environment["sys_platform"], environment["platform_machine"]) != (
        "3.12", "linux", "x86_64"
    ):
        raise ValueError("resolve on the pinned CPython 3.12 Linux amd64 base")
    lines = [
        "# Generated by lock_from_report.py; CPython 3.12 / Linux amd64 only.",
        "# Every dependency is an exact wheel URL with a SHA256 integrity check.",
        "# Update requirements.in and re-resolve intentionally; see README.md.",
        "--require-hashes",
        "--only-binary=:all:",
        "--no-index",
        "",
    ]
    for entry in sorted(report["install"], key=lambda item: item["metadata"]["name"].lower()):
        info = entry["download_info"]
        url = info["url"]
        if entry.get("is_yanked"):
            raise ValueError(f"refusing yanked package: {url}")
        if urlparse(url).scheme != "https" or not urlparse(url).path.endswith(".whl"):
            raise ValueError(f"expected an HTTPS wheel: {url}")
        digest = info["archive_info"]["hashes"]["sha256"]
        if not re.fullmatch(r"[a-f0-9]{64}", digest):
            raise ValueError("missing valid SHA256 digest")
        name = entry["metadata"]["name"]
        version = entry["metadata"]["version"]
        lines.extend([f"# {name}=={version}", f"{name} @ {url} --hash=sha256:{digest}"])
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Locked {len(report['install'])} packages to {args.output}")


if __name__ == "__main__":
    main()
